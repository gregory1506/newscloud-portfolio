create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  target text not null,
  channel text not null,
  region text not null,
  artifact_type text not null,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint subscriptions_target_channel_region_artifact_key
    unique (target, channel, region, artifact_type)
);

create index if not exists subscriptions_active_lookup_idx
  on public.subscriptions (channel, region, artifact_type, active);

create or replace function public.set_subscriptions_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_subscriptions_updated_at on public.subscriptions;
create trigger set_subscriptions_updated_at
before update on public.subscriptions
for each row
execute function public.set_subscriptions_updated_at();

alter table public.subscriptions enable row level security;

revoke all on public.subscriptions from anon, authenticated;

