create table if not exists public.email_recipients (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text,
  client_name text,
  active boolean not null default true,
  delivery_format text not null default 'email_html'
    check (delivery_format in ('email_html')),
  subject_override text,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create trigger set_email_recipients_updated_at
before update on public.email_recipients
for each row
execute function public.set_updated_at();

create table if not exists public.email_deliveries (
  id bigint generated by default as identity primary key,
  run_date date not null,
  recipient_email text not null,
  recipient_name text,
  client_name text,
  status text not null
    check (status in ('sent', 'failed', 'skipped')),
  provider text not null,
  provider_message_id text,
  subject text not null,
  error_message text,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  sent_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint email_deliveries_run_date_recipient_email_key
    unique (run_date, recipient_email)
);

create index if not exists email_deliveries_run_date_idx
  on public.email_deliveries (run_date desc);

create trigger set_email_deliveries_updated_at
before update on public.email_deliveries
for each row
execute function public.set_updated_at();
