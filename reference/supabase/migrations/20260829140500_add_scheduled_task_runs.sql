create table if not exists public.scheduled_task_runs (
  id bigint generated by default as identity primary key,
  task_name text not null,
  logical_key text not null,
  status text not null default 'pending'
    check (status in ('pending', 'running', 'succeeded', 'failed')),
  claim_token uuid,
  lease_expires_at timestamptz,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  last_error text,
  completed_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint scheduled_task_runs_unique_key unique (task_name, logical_key)
);

create index if not exists scheduled_task_runs_status_lease_idx
  on public.scheduled_task_runs (status, lease_expires_at);

create trigger set_scheduled_task_runs_updated_at
before update on public.scheduled_task_runs
for each row
execute function public.set_updated_at();

alter table public.scheduled_task_runs enable row level security;

revoke all on table public.scheduled_task_runs from public;
revoke all on table public.scheduled_task_runs from anon;
revoke all on table public.scheduled_task_runs from authenticated;

create or replace function public.claim_scheduled_task(
  p_task_name text,
  p_logical_key text,
  p_lease_seconds integer default 300,
  p_now timestamptz default timezone('utc', now())
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed_token uuid;
begin
  if nullif(trim(p_task_name), '') is null or nullif(trim(p_logical_key), '') is null then
    raise exception 'task_name and logical_key are required';
  end if;
  if p_lease_seconds < 15 or p_lease_seconds > 3600 then
    raise exception 'lease_seconds must be between 15 and 3600';
  end if;

  insert into public.scheduled_task_runs (task_name, logical_key)
  values (p_task_name, p_logical_key)
  on conflict (task_name, logical_key) do nothing;

  update public.scheduled_task_runs str
  set status = 'running',
      claim_token = gen_random_uuid(),
      lease_expires_at = p_now + make_interval(secs => p_lease_seconds),
      attempt_count = str.attempt_count + 1,
      last_error = null,
      completed_at = null
  where str.task_name = p_task_name
    and str.logical_key = p_logical_key
    and (
      str.status in ('pending', 'failed')
      or (str.status = 'running' and str.lease_expires_at <= p_now)
    )
  returning str.claim_token into claimed_token;

  return claimed_token;
end;
$$;

create or replace function public.finish_scheduled_task(
  p_task_name text,
  p_logical_key text,
  p_claim_token uuid,
  p_status text,
  p_details jsonb default '{}'::jsonb,
  p_error text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_count integer;
begin
  if p_status not in ('succeeded', 'failed') then
    raise exception 'finish status must be succeeded or failed';
  end if;

  update public.scheduled_task_runs str
  set status = p_status,
      details = coalesce(p_details, '{}'::jsonb),
      last_error = p_error,
      completed_at = case when p_status = 'succeeded' then timezone('utc', now()) else null end,
      lease_expires_at = null
  where str.task_name = p_task_name
    and str.logical_key = p_logical_key
    and str.status = 'running'
    and str.claim_token = p_claim_token;

  get diagnostics updated_count = row_count;
  return updated_count = 1;
end;
$$;

revoke execute on function public.claim_scheduled_task(text, text, integer, timestamptz) from public;
revoke execute on function public.claim_scheduled_task(text, text, integer, timestamptz) from anon;
revoke execute on function public.claim_scheduled_task(text, text, integer, timestamptz) from authenticated;
grant execute on function public.claim_scheduled_task(text, text, integer, timestamptz) to service_role;

revoke execute on function public.finish_scheduled_task(text, text, uuid, text, jsonb, text) from public;
revoke execute on function public.finish_scheduled_task(text, text, uuid, text, jsonb, text) from anon;
revoke execute on function public.finish_scheduled_task(text, text, uuid, text, jsonb, text) from authenticated;
grant execute on function public.finish_scheduled_task(text, text, uuid, text, jsonb, text) to service_role;
