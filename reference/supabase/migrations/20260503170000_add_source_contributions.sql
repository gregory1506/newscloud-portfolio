create table if not exists public.source_contributions (
  id bigint generated by default as identity primary key,
  region text not null,
  date date not null,
  provider text not null
    check (provider in ('rss', 'brave_news')),
  source_name text not null,
  source_query text,
  source_url text,
  result_count integer not null default 0
    check (result_count >= 0),
  text_char_count integer not null default 0
    check (text_char_count >= 0),
  token_count integer not null default 0
    check (token_count >= 0),
  status text not null default 'success'
    check (status in ('success', 'empty', 'error')),
  error_message text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint source_contributions_region_date_provider_name_key
    unique (region, date, provider, source_name)
);

create index if not exists source_contributions_date_idx
  on public.source_contributions (date desc);

create trigger set_source_contributions_updated_at
before update on public.source_contributions
for each row
execute function public.set_updated_at();
