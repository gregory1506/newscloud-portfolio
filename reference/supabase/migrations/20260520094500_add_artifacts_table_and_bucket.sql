create table if not exists public.artifacts (
  id bigint generated by default as identity primary key,
  run_date date not null,
  region text not null,
  artifact_type text not null,
  format text not null,
  storage_bucket text not null,
  storage_path text not null,
  content_hash text not null,
  template_version text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint artifacts_run_region_type_format_key unique (run_date, region, artifact_type, format),
  constraint artifacts_metadata_is_object check (jsonb_typeof(metadata) = 'object')
);

create index if not exists artifacts_run_date_idx
  on public.artifacts (run_date desc);

create trigger set_artifacts_updated_at
before update on public.artifacts
for each row
execute function public.set_updated_at();

alter table public.artifacts enable row level security;

revoke all on table public.artifacts from public;
revoke all on table public.artifacts from anon;
revoke all on table public.artifacts from authenticated;

insert into storage.buckets (id, name, public)
values ('artifacts', 'artifacts', false)
on conflict (id) do update
set public = excluded.public;
