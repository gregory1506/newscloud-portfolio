create table if not exists public.delivery_jobs (
  id bigint generated by default as identity primary key,
  run_date date not null,
  region text not null,
  artifact_type text not null,
  channel text not null,
  target text not null,
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'sent', 'failed', 'retry_scheduled', 'skipped')),
  provider text,
  provider_message_id text,
  subject text,
  error_message text,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  attempt_count integer not null default 0,
  last_attempt_at timestamptz,
  next_retry_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint delivery_jobs_unique_target
    unique (run_date, region, artifact_type, channel, target)
);

create index if not exists delivery_jobs_run_date_idx
  on public.delivery_jobs (run_date desc);

create index if not exists delivery_jobs_status_retry_idx
  on public.delivery_jobs (status, next_retry_at);

create trigger set_delivery_jobs_updated_at
before update on public.delivery_jobs
for each row
execute function public.set_updated_at();

alter table public.delivery_jobs enable row level security;

revoke all on table public.delivery_jobs from public;
revoke all on table public.delivery_jobs from anon;
revoke all on table public.delivery_jobs from authenticated;
