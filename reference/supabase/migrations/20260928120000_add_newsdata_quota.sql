-- Account-wide NewsData.io credit reservations shared by the state gatherer
-- (functions/gatherer/main.py) and the district gatherer
-- (functions/gatherer/district_gatherer.py).
--
-- Both gatherers call public.reserve_newsdata_credit(...) immediately before
-- every NewsData HTTP request. The row count per run date and per rolling
-- 15-minute window is the only source of truth for the ceilings, so the limits
-- survive instance restarts and are enforced across instances.
--
-- Deploy order: apply this migration before deploying the gatherer and
-- gatherer-district code (the calling module is shared/newsdata_quota.py; see
-- its docstring for the operator checklist). Code that ships first degrades to
-- "allow the request and log one newsdata_quota_unavailable line per process"
-- because the RPC is missing, so the reverse order is safe for a short window
-- but leaves the account without durable accounting.

create table if not exists public.newsdata_credit_reservations (
  id bigint generated by default as identity primary key,
  run_date date not null,
  source text not null default 'unknown',
  reserved_at timestamptz not null default timezone('utc', now())
);

create index if not exists newsdata_credit_reservations_window_idx
  on public.newsdata_credit_reservations (reserved_at desc);

create index if not exists newsdata_credit_reservations_run_date_idx
  on public.newsdata_credit_reservations (run_date);

alter table public.newsdata_credit_reservations enable row level security;

revoke all on table public.newsdata_credit_reservations from public;
revoke all on table public.newsdata_credit_reservations from anon;
revoke all on table public.newsdata_credit_reservations from authenticated;

-- The provenance rows carry the denial as their status, so the CHECK has to
-- accept it. Without this the upsert raises and the region is marked failed --
-- a quota blip would take the board down instead of thinning it.
do $$
declare
  v_constraint text;
begin
  if to_regclass('public.source_contributions') is null then
    return;
  end if;

  select conname into v_constraint
  from pg_constraint
  where conrelid = 'public.source_contributions'::regclass
    and contype = 'c'
    and pg_get_constraintdef(oid) ilike '%status = any%'
    and pg_get_constraintdef(oid) ilike '%success%';

  if v_constraint is not null then
    execute format('alter table public.source_contributions drop constraint %I', v_constraint);
  end if;

  execute 'alter table public.source_contributions add constraint source_contributions_status_check '
    || 'check (status in (''success'', ''empty'', ''error'', ''quota_deferred'', ''quota_exhausted''))';
end $$;

-- A window denial leaves a region retryable instead of complete, so the
-- gatherer reports ``deferred``. The reconciler retries it (its claim RPC
-- already accepts any status other than ``completed``) and the coverage audit
-- counts it as short until the retry lands. Only the gatherer can defer; the
-- scorer and generator vocabularies are unchanged.
--
-- Guarded so the migration also applies to a bare PostgreSQL that has no
-- region_runs yet, and re-runnable if a name lookup ever misses.
do $$
declare
  v_constraint text;
begin
  if to_regclass('public.region_runs') is null then
    return;
  end if;

  select conname into v_constraint
  from pg_constraint
  where conrelid = 'public.region_runs'::regclass
    and contype = 'c'
    and pg_get_constraintdef(oid) ilike '%gatherer_status%';

  if v_constraint is not null then
    execute format('alter table public.region_runs drop constraint %I', v_constraint);
  end if;

  execute 'alter table public.region_runs add constraint region_runs_gatherer_status_check '
    || 'check (gatherer_status in (''none'', ''running'', ''completed'', ''failed'', ''deferred''))';
end $$;

-- Reserve one credit atomically. Returns:
--   1  the request may proceed
--  -1  the rolling 15-minute ceiling is full (transient: the caller defers the
--      target and the bounded retry path re-attempts it once the window drains)
--  -2  the daily ceiling is full (terminal for this run date: the caller must
--      not retry, because the ceiling cannot move until the next day)
--
-- The reason matters to the caller: a window denial is recoverable in minutes,
-- a daily denial is not, and treating them alike either loses coverage
-- silently or burns retry budget on a ceiling that cannot move.
drop function if exists public.reserve_newsdata_credit(date, text, integer, integer);

create or replace function public.reserve_newsdata_credit(
  p_run_date date,
  p_source text,
  p_daily_limit integer,
  p_window_limit integer
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_window_start timestamptz := now() - interval '15 minutes';
  v_daily_used integer;
  v_window_used integer;
begin
  if p_run_date is null then
    raise exception 'run_date is required';
  end if;
  if p_daily_limit is null or p_daily_limit < 1 then
    raise exception 'daily_limit must be >= 1';
  end if;
  if p_window_limit is null or p_window_limit < 1 then
    raise exception 'window_limit must be >= 1';
  end if;

  -- One constant key serialises every reservation, so the two counts and the
  -- insert below are a single atomic check-and-insert across instances.
  perform pg_advisory_xact_lock(hashtext('newscloud.newsdata_credit_quota'));

  select count(*) into v_daily_used
  from public.newsdata_credit_reservations r
  where r.run_date = p_run_date;

  if v_daily_used >= p_daily_limit then
    return -2;
  end if;

  select count(*) into v_window_used
  from public.newsdata_credit_reservations r
  where r.reserved_at > v_window_start;

  if v_window_used >= p_window_limit then
    return -1;
  end if;

  insert into public.newsdata_credit_reservations (run_date, source)
  values (p_run_date, coalesce(nullif(trim(p_source), ''), 'unknown'));

  return 1;
end;
$$;

revoke execute on function public.reserve_newsdata_credit(date, text, integer, integer) from public;
revoke execute on function public.reserve_newsdata_credit(date, text, integer, integer) from anon;
revoke execute on function public.reserve_newsdata_credit(date, text, integer, integer) from authenticated;
grant execute on function public.reserve_newsdata_credit(date, text, integer, integer) to service_role;
