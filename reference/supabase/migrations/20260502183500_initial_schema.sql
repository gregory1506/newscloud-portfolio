create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.word_frequencies (
  id bigint generated by default as identity primary key,
  region text not null,
  date date not null,
  frequencies jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint word_frequencies_region_date_key unique (region, date),
  constraint word_frequencies_frequencies_is_object
    check (jsonb_typeof(frequencies) = 'object')
);

create index if not exists word_frequencies_date_idx
  on public.word_frequencies (date desc);

create trigger set_word_frequencies_updated_at
before update on public.word_frequencies
for each row
execute function public.set_updated_at();

