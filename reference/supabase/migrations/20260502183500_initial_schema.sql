  region text not null,
  date date not null,
  storage_url text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint generated_images_region_date_key unique (region, date)
);

create index if not exists generated_images_date_idx
  on public.generated_images (date desc);

create trigger set_generated_images_updated_at
before update on public.generated_images
for each row
execute function public.set_updated_at();

create table if not exists public.regional_sentiment (
  id bigint generated by default as identity primary key,
  region text not null,
  date date not null,
  sentiment_score numeric(4, 2) not null,
  leaning_score numeric(4, 2) not null,
  top_positive_words jsonb not null default '[]'::jsonb,
  top_negative_words jsonb not null default '[]'::jsonb,
  left_indicators jsonb not null default '[]'::jsonb,
  right_indicators jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint regional_sentiment_region_date_key unique (region, date),
  constraint regional_sentiment_score_range
    check (sentiment_score >= 0 and sentiment_score <= 10),
  constraint regional_leaning_score_range
    check (leaning_score >= 0 and leaning_score <= 5),
  constraint regional_sentiment_positive_is_array
    check (jsonb_typeof(top_positive_words) = 'array'),
  constraint regional_sentiment_negative_is_array
    check (jsonb_typeof(top_negative_words) = 'array'),
  constraint regional_sentiment_left_is_array
    check (jsonb_typeof(left_indicators) = 'array'),
  constraint regional_sentiment_right_is_array
    check (jsonb_typeof(right_indicators) = 'array')
);

create index if not exists regional_sentiment_date_idx
  on public.regional_sentiment (date desc);

create trigger set_regional_sentiment_updated_at
before update on public.regional_sentiment
for each row
execute function public.set_updated_at();

